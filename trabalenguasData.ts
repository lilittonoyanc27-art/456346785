export function lookupWordArmenian(rawWord: string): string {
  const clean = rawWord
    .toLowerCase()
    .replace(/^[¡¿"'«(]+|[.,;:!?)"'»]+$/g, '');
  return WORD_DICTIONARY_HY[clean] ?? 'Բառարանային թարգմանություն';
}
